// Generates INDEX.md, the finder an agent reads after AGENTS.md (D10): every component, block,
// page recipe and pattern with its intent keywords, what it uses and whether it needs livewire.
// `--check` fails when the committed INDEX.md differs from what the cards say.

import { readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { readCards, type Card, type Tier } from './cards'

const root = join(import.meta.dir, '..')
const target = join(root, 'INDEX.md')

const titles: Record<Tier, string> = {
  primitive: 'Primitives: props and emits only, no livewire',
  layout: 'Layout: the shell and the page frame',
  block: 'Blocks: composed and livewire-wired',
  page: 'Page recipes: whole pages composing blocks',
  pattern: 'Patterns: intent guides',
}

export function render(cards: Card[]): string {
  const lines: string[] = [
    '# INDEX',
    '',
    'Generated by `scripts/index.ts` from the cards\' front matter; do not edit, run `just index`.',
    'Find by intent (Ctrl-F a word you would say), open the card, then the code next to it.',
    '',
    '| Tier | Count |',
    '|------|-------|',
  ]
  for (const tier of Object.keys(titles) as Tier[]) {
    lines.push(`| ${tier} | ${cards.filter(card => card.tier === tier).length} |`)
  }
  for (const tier of Object.keys(titles) as Tier[]) {
    const rows = cards.filter(card => card.tier === tier)
    if (rows.length === 0) continue
    lines.push('', `## ${titles[tier]}`, '', '| Name | Intent | Uses | Livewire | Status | Summary |', '|------|--------|------|----------|--------|---------|')
    for (const card of rows) {
      const link = `[${card.name}](${card.path})`
      lines.push(`| ${link} | ${card.intent.join(', ')} | ${card.uses.join(', ')} | ${card.livewire ? 'yes' : 'no'} | ${card.status} | ${card.summary.replace(/\|/g, '\\|')} |`)
    }
  }
  lines.push('', '## By intent', '', 'Every intent keyword and the pieces that answer it.', '')
  const byIntent = new Map<string, Card[]>()
  for (const card of cards) for (const intent of card.intent) byIntent.set(intent, [...(byIntent.get(intent) ?? []), card])
  for (const [intent, owners] of [...byIntent.entries()].sort(([a], [b]) => a.localeCompare(b))) {
    lines.push(`- **${intent}**: ${owners.map(card => `[${card.name}](${card.path})`).join(', ')}`)
  }
  return lines.join('\n') + '\n'
}

if (import.meta.main) {
  const text = render(readCards(root))
  if (process.argv.includes('--check')) {
    const current = (() => { try { return readFileSync(target, 'utf8') } catch { return '' } })()
    if (current !== text) {
      console.error('INDEX.md is stale: run `just index` and commit the result')
      process.exit(1)
    }
    console.log('INDEX.md is current')
  } else {
    writeFileSync(target, text)
    console.log(`wrote ${target}`)
  }
}
